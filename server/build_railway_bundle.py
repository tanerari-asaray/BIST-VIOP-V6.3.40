"""Build/check the single TypeScript file accepted by Railway Functions. No secrets are read."""
import argparse
from pathlib import Path

root = Path(__file__).resolve().parent

def strip_module(source: str) -> str:
    return "\n".join(
        line.removeprefix("export ")
        for line in source.splitlines()
        if not (line.startswith("import ") and ('"./' in line or "'./" in line))
        and not (line.startswith("import ") and '"node:crypto"' in line)
    ) + "\n"

def render() -> str:
    files = ("gateway_diagnostics.mjs", "market_proxy.ts", "railway_gateway_function.ts")
    return (
        "// GENERATED by server/build_railway_bundle.py; edit the source modules, then regenerate.\n"
        'import { timingSafeEqual } from "node:crypto";\n\n'
        + "\n".join("// SOURCE: " + name + "\n" + strip_module((root / name).read_text()) for name in files)
    )

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = root / "railway_function_bundle.ts"
    expected = render()
    if args.check:
        if not target.exists() or target.read_text() != expected:
            raise SystemExit("Railway bundle differs from reviewed modules; regenerate it.")
        print("Railway bundle matches all three source modules.")
    else:
        target.write_text(expected)
        print(target.name)
